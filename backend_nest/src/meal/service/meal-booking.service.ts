  private isBeforeDeadline(todayNow: Date, dateStr: string, deadlineTime: string): boolean {
    const { h, m } = this.parseTime(deadlineTime);
    const deadline = new Date(dateStr);
    deadline.setHours(h, m, 0, 0);
    return todayNow < deadline;
  }

  private calcDeadlinePrevDay(targetDate: string, timeStr: string): Date {
    const date = new Date(targetDate);
    date.setDate(date.getDate() - 1);
    const { h, m } = this.parseTime(timeStr);
    date.setHours(h, m, 0, 0);
    return date;
  }

