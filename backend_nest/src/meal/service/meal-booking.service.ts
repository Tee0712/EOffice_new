  async getMyRegistrations(
    userId: string,
    query: { page: number; limit: number; status?: string; start_date?: string; end_date?: string },
  ) {
    const { page, limit, status, start_date, end_date } = query;
    const skip = (page - 1) * limit;

    const qb = this.registrationRepo
      .createQueryBuilder('r')
      .leftJoinAndSelect('r.items', 'item')
      .leftJoinAndSelect('item.mealSession', 'session')
      .leftJoinAndSelect('item.dailyMenu', 'menu')
      .where('r.userId = :userId', { userId });

    if (status) qb.andWhere('r.status = :status', { status });
    if (start_date) qb.andWhere('r.date >= :start_date', { start_date });
    if (end_date) qb.andWhere('r.date <= :end_date', { end_date });

    const [items, total] = await qb
      .orderBy('r.date', 'DESC')
      .skip(skip)
      .take(limit)
      .getManyAndCount();

    const registrationIds = items.map((r) => Number(r.id)).filter((id) => Number.isFinite(id) && id > 0);
    const checkedInByRegistration = new Map<number, number>();
    if (registrationIds.length > 0) {
      const idParams = registrationIds.map((_, idx) => `@${idx}`).join(', ');
      const rows: Array<{ registration_id: number; checkin_count: number }> = await this.dataSource.query(
        `
          SELECT
            registration_id,
            COUNT(1) AS checkin_count
          FROM meal_checkins
          WHERE registration_id IN (${idParams})
          GROUP BY registration_id
        `,
        registrationIds,
      );
      rows.forEach((row) => {
        const regId = Number((row as any).registration_id);
        const count = Number((row as any).checkin_count || 0);
        if (Number.isFinite(regId)) checkedInByRegistration.set(regId, Math.max(0, count));
      });
    }

    items.forEach((r: any) => {
      const regId = Number(r?.id);
      const checkedInMealCount = Number(checkedInByRegistration.get(regId) || 0);
      r.checkedInMealCount = checkedInMealCount;
      r.checked_in_meal_count = checkedInMealCount;
    });

    return { items, total, page, limit };
  }

