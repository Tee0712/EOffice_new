  private inferSlotFromSession(
    mealSessionId?: number | null,
    mealSessionName?: string,
    mealSessionStart?: string,
  ): 'breakfast' | 'lunch' | 'dinner' {
    if (mealSessionId === 1) return 'breakfast';
    if (mealSessionId === 2) return 'lunch';
    if (mealSessionId === 3) return 'dinner';

    if (mealSessionStart) {
      const hour = Number(String(mealSessionStart).split(':')[0]);
      if (!Number.isNaN(hour)) {
        if (hour < 10) return 'breakfast';
        if (hour < 16) return 'lunch';
        return 'dinner';
      }
    }

    return this.normalizeSlotFromSessionName(mealSessionName || '');
  }

