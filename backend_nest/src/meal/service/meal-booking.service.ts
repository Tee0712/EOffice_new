  async getAdminDashboard(query: { date?: string; view?: 'day' | 'week' | 'month' }) {
    const anchorDate = query.date || this.formatDateOnly(new Date());
    const view = query.view || 'day';
    const { startDate, endDate, points } = this.getRangeByView(anchorDate, view);
    const yesterday = this.formatDateOnly(this.addDays(this.parseDateOnly(anchorDate), -1));

    const rowsAll = await this.getAdminRegistrations({});

    const normalize = (v: any): string => {
      if (!v) return '';
      if (v instanceof Date) return this.formatDateOnly(v);
      if (typeof v === 'string') {
        if (v.includes('T')) return v.split('T')[0];
        if (v.includes(' ')) return this.formatDateOnly(new Date(v));
        return v.slice(0, 10);
      }
      return String(v);
    };

    const rowsInRange = (rowsAll || []).filter((r: any) => {
      const d = normalize(r.date);
      return d >= startDate && d <= endDate;
    });
    const rowsToday = (rowsAll || []).filter((r: any) => normalize(r.date) === anchorDate);
    const rowsYesterday = (rowsAll || []).filter((r: any) => normalize(r.date) === yesterday);

    let trend: Array<{ date: string; total: number; breakfast: number; lunch: number; dinner: number; cancelled: number }> = [];
    let todaySummary = { breakfast: 0, lunch: 0, dinner: 0, total: 0, cancelled: 0 };
    let yesterdaySummary = { breakfast: 0, lunch: 0, dinner: 0, total: 0, cancelled: 0 };

    // Use one unified source (rowsAll/getAdminRegistrations) for all widgets
    // so cards, trend, department and ratios always stay in sync.
    const byDate = new Map<string, any>();
    for (const p of points) {
      byDate.set(p, { breakfast: 0, lunch: 0, dinner: 0, cancelled: 0 });
    }

    const consumeRow = (row: any) => {
      const d = normalize(row.date);
      if (!byDate.has(d)) return;
      const status = String(row.status || '').toLowerCase();
      const bucket = byDate.get(d);
      if (status === 'cancelled' || status === 'auto_cut') {
        bucket.cancelled += 1;
        return;
      }
      const meals = Array.isArray(row.meals) && row.meals.length > 0 ? row.meals : [{ slot: row.menu?.meal_slot }];
      meals.forEach((meal: any) => {
        const slot = this.normalizeSlotToken(String(meal?.slot || row.menu?.meal_slot || ''));
        if (slot === 'breakfast') bucket.breakfast += 1;
        else if (slot === 'lunch') bucket.lunch += 1;
        else if (slot === 'dinner') bucket.dinner += 1;
      });
    };
    rowsInRange.forEach(consumeRow);

    trend = points.map((p) => {
      const b = byDate.get(p) || { breakfast: 0, lunch: 0, dinner: 0, cancelled: 0 };
      return {
        date: p,
        total: b.breakfast + b.lunch + b.dinner,
        breakfast: b.breakfast,
        lunch: b.lunch,
        dinner: b.dinner,
        cancelled: b.cancelled,
      };
    });

    const t = trend.find((x) => x.date === anchorDate);
    const y = trend.find((x) => x.date === yesterday);
    if (t) todaySummary = { ...t };
    if (y) yesterdaySummary = { ...y };

    const cards = {
      breakfast: {
        value: todaySummary.breakfast,
        delta: todaySummary.breakfast - yesterdaySummary.breakfast,
      },
      lunch: {
        value: todaySummary.lunch,
        delta: todaySummary.lunch - yesterdaySummary.lunch,
      },
      dinner: {
        value: todaySummary.dinner,
        delta: todaySummary.dinner - yesterdaySummary.dinner,
      },
      total: {
        value: todaySummary.total,
        delta: todaySummary.total - yesterdaySummary.total,
      },
    };

    const statusStats = {
      total: rowsInRange.length,
      registered: 0,
      cancelled: 0,
      autoCut: 0,
    };
    for (const reg of rowsInRange) {
      const status = String(reg.status || '').toLowerCase();
      const reason = String(reg.cancel_reason || reg.cancelReason || '').toLowerCase();
      if (status === 'auto_cut') {
        statusStats.autoCut += 1;
        statusStats.cancelled += 1;
      } else if (status === 'cancelled') {
        statusStats.cancelled += 1;
        if (reason.includes('tu dong') || reason.includes('auto') || reason.includes('cong tac') || reason.includes('nghi phep')) {
          statusStats.autoCut += 1;
        }
      } else {
        statusStats.registered += 1;
      }
    }

    const ratioBase = statusStats.total || 1;
    const statusRatio = {
      ...statusStats,
      registeredRate: Number(((statusStats.registered / ratioBase) * 100).toFixed(1)),
      cancelledRate: Number(((statusStats.cancelled / ratioBase) * 100).toFixed(1)),
      autoCutRate: Number(((statusStats.autoCut / ratioBase) * 100).toFixed(1)),
    };

    const deptMap = new Map<string, { name: string; count: number }>();
    rowsToday.forEach((row: any) => {
      const key = String(row.department_id || 'unknown');
      const name = row.department_name || 'Khac';
      const mealCount = Array.isArray(row.meals) ? row.meals.length : 1;
      const current = deptMap.get(key) || { name, count: 0 };
      current.count += mealCount;
      deptMap.set(key, current);
    });

    const totalDeptMeals = Array.from(deptMap.values()).reduce((sum, d) => sum + d.count, 0);
    const departmentDistribution = Array.from(deptMap.values())
      .sort((a, b) => b.count - a.count)
      .map((d) => ({
        name: d.name,
        count: d.count,
        percent: totalDeptMeals > 0 ? Number(((d.count / totalDeptMeals) * 100).toFixed(1)) : 0,
      }));

    const todayList = rowsToday.slice(0, 8).map((r: any, idx: number) => ({
      stt: idx + 1,
      userName: r.user_name,
      email: r.email,
      departmentName: r.department_name,
      meals: r.meals || [],
      note: r.note || '',
      status: r.status,
    }));

    return {
      date: anchorDate,
      view,
      range: { startDate, endDate },
      cards,
      trend,
      statusRatio,
      departmentDistribution,
      realtime: {
        todayTotalMeals: todaySummary.total,
        updatedAt: new Date().toISOString(),
      },
      todayList,
    };
  }
  async getMyStats(userId: string, startDate: string, endDate: string) {
    const regs = await this.registrationRepo
      .createQueryBuilder('r')
      .leftJoinAndSelect('r.items', 'item')
      .where('r.userId = :userId', { userId })
      .andWhere('r.date >= :startDate AND r.date <= :endDate', { startDate, endDate })
      .getMany();

    const countMeals = (r: MealBookingEntity) =>
      Array.isArray(r.items) && r.items.length > 0 ? r.items.length : 0;

    const registrationIds = regs
      .map((r) => Number(r?.id))
      .filter((id) => Number.isFinite(id) && id > 0);
    let completedFromCheckins = 0;
    if (registrationIds.length > 0) {
      const params = registrationIds.map((_, idx) => `@${idx}`).join(', ');
      const completedCountRows: Array<{ completed_count: number }> = await this.dataSource.query(
        `
        SELECT COUNT(DISTINCT c.id) AS completed_count
        FROM meal_checkins c
        WHERE c.registration_id IN (${params})
        `,
        registrationIds,
      );
      completedFromCheckins = Number(completedCountRows?.[0]?.completed_count || 0);
    }

    let totalRegisteredMeals = 0;
    let cancelledMeals = 0;
    let totalCost = 0;

    regs.forEach((r) => {
      const mealCount = countMeals(r);
      const status = String(r?.status || '').toLowerCase();
      const isCancelled = status === 'cancelled' || status === 'auto_cut';

      if (isCancelled) {
        cancelledMeals += mealCount;
        return;
      }

      totalRegisteredMeals += mealCount;

      const itemCost = Array.isArray(r?.items)
        ? r.items.reduce((sum, item) => sum + Number(item?.priceAtTime || 0), 0)
        : 0;
      const resolvedCost = itemCost > 0 ? itemCost : Number(r?.totalCost || 0);
      totalCost += Number.isFinite(resolvedCost) ? resolvedCost : 0;
    });

    const normalizedCompleted = Math.min(
      totalRegisteredMeals,
      Math.max(0, completedFromCheckins),
    );
    const upcomingFromCheckins = Math.max(0, totalRegisteredMeals - normalizedCompleted);

    return {
      total_registered: totalRegisteredMeals,
      upcoming: upcomingFromCheckins,
      completed: normalizedCompleted,
      cancelled: cancelledMeals,
      total_cost: totalCost,
      total_refunded: regs.reduce((sum, r) => sum + Number(r.refundAmount), 0),
    };
  }
