  async bulkRegister(userId: string, dto: BulkRegisterDto) {
    const settings = await this.getSettings();
    if (!settings.allowBulkRegistration) {
      throw new BadRequestException('Hệ thống không cho phép đăng ký hàng loạt');
    }

    let mealSessionIds: number[] = 'meal_session_ids' in dto && Array.isArray(dto.meal_session_ids)
      ? (dto.meal_session_ids as number[]).filter((x): x is number => Number.isInteger(x) && x > 0)
      : [];

    if (!mealSessionIds.length && 'template_id' in dto && dto.template_id) {
      const template = await this.dataSource.getRepository(MealTemplateEntity).findOne({
        where: [{ id: (dto as any).template_id, userId }, { id: (dto as any).template_id, userId: IsNull() }],
      });

      if (template?.mealSessions) {
        try {
          const parsed = JSON.parse(template.mealSessions);
          if (Array.isArray(parsed)) {
            mealSessionIds = parsed
              .map((x) => Number(x))
              .filter((x): x is number => Number.isInteger(x) && x > 0);
          }
        } catch {
          mealSessionIds = [];
        }
      }
    }

    if (!mealSessionIds.length) {
      throw new BadRequestException('Cần truyền meal_session_ids hoặc template_id hợp lệ');
    }

    const start = new Date(dto.start_date);
    const end = new Date(dto.end_date);
    const daysOfWeek: number[] = ('days_of_week' in dto && Array.isArray(dto.days_of_week)
      ? dto.days_of_week
      : [0, 1, 2, 3, 4, 5, 6])
      .map((x) => Number(x))
      .filter((x): x is number => Number.isInteger(x) && x >= 0 && x <= 6);
    if (!daysOfWeek.length) {
      throw new BadRequestException('days_of_week khong hop le');
    }

    const now = new Date();
    let createdCount = 0;
    const skipped: string[] = [];

    for (let d = new Date(start); d <= end; d.setDate(d.getDate() + 1)) {
      const dayOfWeek = d.getDay(); // 0=Sun..6=Sat
      if (!daysOfWeek.includes(dayOfWeek)) continue;

      const dateStr = d.toISOString().split('T')[0];
      const deadline = this.calcDeadlinePrevDay(dateStr, settings.registrationDeadlineTime);
      if (now > deadline) {
        skipped.push(dateStr);
        continue;
      }

      const existing = await this.registrationRepo.findOne({ where: { userId, date: dateStr } });
      if (existing) {
        skipped.push(dateStr);
        continue;
      }

      const menus = await this.getMenusForDate(dateStr, mealSessionIds);
      if (menus.length !== mealSessionIds.length) {
        skipped.push(dateStr);
        continue;
      }

      const totalCost = menus.reduce((sum, m) => sum + Number(m.price), 0);

      const queryRunner = this.dataSource.createQueryRunner();
      await queryRunner.connect();
      await queryRunner.startTransaction();
      try {
        const registration = await queryRunner.manager.save(MealBookingEntity, {
          userId,
          date: dateStr,
          status: 'upcoming',
          totalCost,
          note: (dto as any).note ?? null,
          registeredAt: now,
        });

        const items = menus.map((m) =>
          queryRunner.manager.create(RegistrationItemEntity, {
            registrationId: registration.id,
            mealSessionId: m.mealSessionId,
            dailyMenuId: m.id,
            priceAtTime: Number(m.price),
          }),
        );
        await queryRunner.manager.save(RegistrationItemEntity, items);

        await queryRunner.manager.save(RegistrationHistoryEntity, {
          registrationId: registration.id,
          action: 'created',
          description: `Đăng ký ${menus.length} bữa: ${menus.map((m) => m.mealSession?.name ?? m.mealSessionId).join(' + ')}`,
          changedBy: userId,
        });

        await queryRunner.commitTransaction();
        createdCount++;
      } catch {
        await queryRunner.rollbackTransaction();
        skipped.push(dateStr);
      } finally {
        await queryRunner.release();
      }
    }

    return { created_count: createdCount, skipped_dates: skipped };
  }

